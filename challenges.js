/* ============================================================
   GET ONE CHALLENGE
============================================================ */

window.ZIVOZONE_CHALLENGES.get = function(id) {

    return this[id] || null;

};


/* ============================================================
   GET NORMAL CHALLENGES
============================================================ */

window.ZIVOZONE_CHALLENGES.getAll = function() {

    return Object.values(this)

        .filter(

            challenge =>
                challenge &&
                challenge.questions &&
                !challenge.special

        );

};


/* ============================================================
   QUESTION COPY
============================================================ */

window.ZIVOZONE_CHALLENGES.cloneQuestions =
    function(id) {

        const challenge =
            this.get(id);

        if (
            !challenge ||
            !Array.isArray(challenge.questions)
        ) {

            return [];

        }


        return challenge.questions.map(

            question => ({

                ...question,

                a:
                    [...question.a]

            })

        );

    };
