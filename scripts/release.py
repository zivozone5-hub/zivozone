#!/usr/bin/env python3
"""Stamp one version everywhere and regenerate the service-worker precache list from index.html.

usage: python3 scripts/release.py 1219.0
Touches: index.html + stories/*/index.html (?v=), sw.js (cache name + SHELL), core/boot.js and core/config.js (version strings).
Why: the old setup listed files by hand in three places and drifted (stale cache names, missing files).
"""
import re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_bundle as bb
import build_css

ROOT = Path(__file__).resolve().parent.parent
ver = sys.argv[1] if len(sys.argv) > 1 else None
if not ver or not re.fullmatch(r"\d+\.\d+", ver):
    sys.exit("usage: release.py <major.minor>   e.g. 1219.0")
major = ver.split(".")[0]

html_p = ROOT / "index.html"
html = re.sub(r"\?v=\d+\.\d+", f"?v={ver}", html_p.read_text(encoding="utf-8"))
html_p.write_text(html, encoding="utf-8")

# V1229: story pages are full app shells with their own ?v= stamps; keep them on the same version.
for sp in sorted((ROOT / "stories").glob("*/index.html")):
    sp.write_text(re.sub(r"\?v=\d+\.\d+", f"?v={ver}", sp.read_text(encoding="utf-8")), encoding="utf-8")

# V1229: config.js used to keep a stale hand-written version (it said 1188 while the site was 1228).
cfg_p = ROOT / "core" / "config.js"
cfg = cfg_p.read_text(encoding="utf-8")
cfg = re.sub(r"APP_VERSION: '[^']*'", f"APP_VERSION: '{ver}'", cfg)
cfg = re.sub(r"CORE_VERSION: '[^']*'", f"CORE_VERSION: '{ver}-clean-core'", cfg)
cfg_p.write_text(cfg, encoding="utf-8")

# V1229.4: rebuild dist/app.bundle.js from the (now version-stamped) source files, and make sure
# every page's bundle <script> tag exists and carries the current version. Must run AFTER the
# config.js/boot.js stamping above so the bundle embeds the new version strings, not stale ones.
bb.build()
for p in [ROOT / "index.html"] + sorted((ROOT / "stories").glob("*/index.html")):
    bb.rewrite_page(p, bb.manifest_files(), ver)
# V1230.67: modules deliberately left out of the eager bundle (currently just forensic-case-core.js
# — see LAZY_MODULES in build_bundle.py) still need their own minified dist/lazy/ copy refreshed on
# every release, same as the eager bundle above.
for rel, out, before, after, did_minify in bb.build_lazy_modules():
    print(f"lazy module {rel} -> {out.relative_to(ROOT)} ({before} -> {after} bytes, {'minified' if did_minify else 'copied (unminified)'})")
# V1230.67: minified dist/styles/ copies of core/styles/*.css, same split as the JS bundle above.
for name, before, after, did_minify in build_css.build():
    print(f"css {name} -> dist/styles/{name} ({before} -> {after} bytes, {'minified' if did_minify else 'copied (unminified)'})")
# the bundle tag's version may have just changed by the rewrite above; keep `html` (used below for the
# SW precache list) in sync with what is actually on disk.
html = html_p.read_text(encoding="utf-8")

# Local, versioned code/style assets referenced by index.html become the precache shell.
refs = re.findall(r'(?:src|href)="((?!https?:)[^"#]+\.(?:js|css)\?v=[\d.]+)"', html)
shell = ["/", "/index.html"] + ["/" + r for r in dict.fromkeys(refs)] + [
    "/assets/icons/zivo-192.png", "/assets/icons/zivo-512.png", "/manifest.webmanifest"]

sw_p = ROOT / "sw.js"
sw = sw_p.read_text(encoding="utf-8")
sw = re.sub(r"const CACHE='[^']*';", f"const CACHE='zivozone-shell-v{major}';", sw, count=1)
sw = re.sub(r"const SHELL=\[.*?\n\];", "const SHELL=[\n  " + ",\n  ".join(f"'{s}'" for s in shell) + "\n];", sw, count=1, flags=re.S)
sw_p.write_text(sw, encoding="utf-8")

boot_p = ROOT / "core" / "boot.js"
boot = boot_p.read_text(encoding="utf-8")
boot = re.sub(r"r\.version='\d+'", f"r.version='{major}'", boot)
boot = re.sub(r"version:'\d+',diagnostics", f"version:'{major}',diagnostics", boot)
boot_p.write_text(boot, encoding="utf-8")

# V1230.55: the 6 per-language homepage variants (/en/, /zh/, /hi/, /es/, /fr/, /fa/ — see
# scripts/prerender-lang-home.mjs) are full clones of index.html with translated <head> metadata.
# They were previously only ever generated by hand-running that script once (V1230.20) and then
# never again — every later change to index.html (new sections, new ?v= stamp, bundle changes)
# silently left them stale, the exact same "page looks current but isn't" risk qa_bundle_freshness.py
# exists to catch for the JS bundle. Regenerating them here, every release, after index.html/the
# bundle are already fully stamped for `ver` — and BEFORE the sitemap <lastmod> pass below, so that
# pass picks up each page's freshly-written mtime rather than a stale one from the previous release.
import subprocess
subprocess.run(["node", str(ROOT / "scripts" / "prerender-lang-home.mjs")], check=True, cwd=ROOT)

# V1229.15 — SEO: keep sitemap.xml's <lastmod> honest and current automatically, instead of it
# silently going stale. Uses each page's own real filesystem mtime (when it was actually last
# edited), not today's date for every URL, so lastmod means what search engines expect it to mean.
import datetime
sitemap_p = ROOT / "sitemap.xml"
sitemap = sitemap_p.read_text(encoding="utf-8")
PAGE_FOR_URL = {
    "https://zivozone.com/": ROOT / "index.html",
    "https://zivozone.com/privacy/": ROOT / "privacy" / "index.html",
    "https://zivozone.com/terms/": ROOT / "terms" / "index.html",
}
for p in sorted((ROOT / "stories").glob("tale-*/index.html")):
    PAGE_FOR_URL[f"https://zivozone.com/stories/{p.parent.name}"] = p
# V1230.55: the 6 per-language homepages above now regenerate every release, so their <lastmod>
# should track that too (prerender-lang-home.mjs's own sitemap-append code only ever ran once, the
# first time each URL was created, and never touched its lastmod again on later regenerations).
for lang in ["en", "zh", "hi", "es", "fr", "fa"]:
    PAGE_FOR_URL[f"https://zivozone.com/{lang}/"] = ROOT / lang / "index.html"

def with_lastmod(m):
    url = m.group(1)
    page = PAGE_FOR_URL.get(url)
    if not page or not page.exists():
        return m.group(0)
    mtime = datetime.datetime.fromtimestamp(page.stat().st_mtime, tz=datetime.timezone.utc).date().isoformat()
    return f"<url><loc>{url}</loc><lastmod>{mtime}</lastmod></url>"

sitemap = re.sub(r"<url><loc>([^<]+)</loc>(?:<lastmod>[^<]*</lastmod>)?</url>", with_lastmod, sitemap)
sitemap_p.write_text(sitemap, encoding="utf-8")

# V1230.127 — durably record what shipped each release so the admin panel's "آخر تحديثات الموقع"
# panel (core/modules/admin.js, loadChangelog()) can show real history via a cheap static-file
# fetch (zero Firestore cost), instead of the admin having no way to see what changed and when.
# Usage: python3 scripts/release.py <ver> ["<short Arabic summary of what this release changed>"]
# The note is optional so release.py keeps working unchanged if it's omitted (a generic fallback
# is recorded instead) — but passing one is how future releases stay genuinely informative.
import json
changelog_p = ROOT / "data" / "changelog.json"
note = sys.argv[2] if len(sys.argv) > 2 else f"إصدار {ver}"
try:
    changelog = json.loads(changelog_p.read_text(encoding="utf-8")) if changelog_p.exists() else []
except Exception:
    changelog = []
changelog = [e for e in changelog if e.get("version") != ver]  # re-running the same version replaces its entry, doesn't duplicate it
changelog.insert(0, {"version": ver, "date": datetime.date.today().isoformat(), "summary": note})
changelog = changelog[:40]
changelog_p.write_text(json.dumps(changelog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

print(f"stamped {ver}: {len(shell)} precache entries")
