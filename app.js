function saveLeaderboard() {

  let board =
    getLeaderboard();


  const existing =
    board.findIndex(
      item =>
        item.name ===
        player.name
    );


  const playerData = {

    name:
      player.name,

    points:
      player.points,

    level:
      player.level

  };


  if (
    existing >= 0
  ) {

    board[existing] =
      playerData;

  }

  else {

    board.push(
      playerData
    );

  }


  board.sort(
    (a, b) =>
      b.points -
      a.points
  );


  board =
    board.slice(
      0,
      100
    );


  localStorage.setItem(
    "globalChallengeLeaderboard",
    JSON.stringify(
      board
    )
  );

}


