/* =====================================================
   ANSWER
===================================================== */

function submitAnswer(index) {

  if (
    currentGame.locked
  ) {

    return;

  }


  currentGame.locked =
    true;


  clearInterval(
    timerInterval
  );


  const elapsed =
    (
      Date.now() -
      currentGame.startedAt
    ) / 1000;


  currentGame.totalTime +=
    elapsed;


  const q =
    currentGame
      .questions[
        currentGame.index
      ];


  const buttons =
    [
      ...document
        .querySelectorAll(
          ".answer"
        )
    ];


  buttons.forEach(
    (button, i) => {

      button.disabled =
        true;


      if (
        q.answers[i]
          .correct
      ) {

        button.classList.add(
          "correct"
        );

      }


      if (
        i === index &&
        !q.answers[i]
          .correct
      ) {

        button.classList.add(
          "wrong"
        );

      }

    }
  );


  const correct =
    index >= 0 &&
    q.answers[index] &&
    q.answers[index]
      .correct;


  const feedback =
    document.getElementById(
      "feedback"
    );


  if (correct) {

    currentGame.correct++;


    const speedBonus =
      Math.max(
        0,
        Math.round(
          (
            getTimeLimit() -
            elapsed
          ) * 2
        )
      );


    const points =
      (
        q.difficulty *
        20
      ) +
      speedBonus;


    currentGame.score +=
      points;


    feedback.textContent =
      `${t("right")} +${points}`;

  }

  else {

    feedback.textContent =
      index === -1
        ? t("timeout")
        : t("wrong");

  }


  /*

     IMPORTANT:

     Keep result visible
     for 2 seconds.

  */

  setTimeout(
    () => {

      currentGame.index++;


      if (
        currentGame.index >=
        currentGame.questions.length
      ) {

        finishGame();

      }

      else {

        renderQuestion();

      }

    },
    2000
  );

}


/* =====================================================
   FINISH GAME
===================================================== */

