function getAgeDifficulty() {

  const age =
    Number(player.age) || 18;

  if (age <= 8)
    return 1;

  if (age <= 12)
    return 2;

  if (age <= 15)
    return 3;

  if (age <= 18)
    return 4;

  if (age <= 25)
    return 5;

  if (age <= 35)
    return 6;

  if (age <= 50)
    return 7;

  return 8;

}


function getDifficulty() {

  const ageLevel =
    getAgeDifficulty();

  const playerLevel =
    Math.min(
      10,
      player.level
    );

  return Math.min(
    10,
    Math.max(
      1,
      Math.round(
        (ageLevel + playerLevel) / 2
      )
    )
  );

}


/* =====================================================
   QUESTIONS GENERATOR
===================================================== */

function generateQuestions(type) {

  const bank =
    questionBank[type];

  const difficulty =
    getDifficulty();


  let suitable =
    bank.filter(q => {

      return (
        Math.abs(
          q.difficulty -
          difficulty
        ) <= 4
      );

    });


  if (!suitable.length) {

    suitable = bank;

  }


  const randomized =
    shuffle(suitable);


  const questions = [];


  for (
    let i = 0;
    i < 10;
    i++
  ) {

    const source =
      randomized[
        i % randomized.length
      ];


    const answerObjects =
      source.answers.map(
        (text, index) => ({

          text,
          correct:
            index ===
            source.correct

        })
      );


    questions.push({

      question:
        source.q,

      difficulty:
        source.difficulty,

      answers:
        shuffle(
          answerObjects
        )

    });

  }


  return questions;

}


