/* ZIVOZONE V1230.104 — site-wide search (Stories + Academy), fully localized.

   WHY: two real content libraries exist on the site — Stories (core/modules/rooms.js) and the
   Academy (data/academy/, static pages generated by scripts/prerender-academy.mjs) — and until now
   neither had any way to be found except by browsing to it directly. This adds one small, shared
   search box (a button in the header that opens an overlay with a live-filtered result list),
   following the exact same self-mounting module pattern every other feature here uses (see
   player-hub.js's mount()/open()/close()).

   LANGUAGE: this does NOT search all 7 languages at once — it searches whichever language is
   currently selected, against that language's own localized index.json (same localize()
   convention rooms.js already uses for story content), so a Spanish-speaking visitor searching
   "control" gets Spanish titles back, not Arabic ones that happen to contain matching substrings.
   Switching the site's language and reopening search switches what's searched, automatically —
   there is nothing to wire per language beyond the data files already carrying real translations.
*/
(() => {
  "use strict";
  if (window.ZIVOZONE_SEARCH?.__canonical) return;

  const esc = window.ZIVOZONE_ESC || (s => String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#039;" }[c])));
  const t = k => { try { return window.zivoT ? window.zivoT(k) : (window.ZIVOZONE_I18N?.tr?.(k) || k); } catch (_) { return k; } };
  const fmt = (k, vars) => Object.entries(vars || {}).reduce((s, [key, val]) => s.split(`{${key}}`).join(val), t(k));
  const LANG = () => { try { return window.ZIVOZONE_I18N?.get?.() || "ar"; } catch (_) { return "ar"; } };
  const dir = () => window.ZIVOZONE_I18N?.dir?.[LANG()] || "rtl";
  // Same convention as rooms.js's localize(): the Arabic file is the original, every other
  // language is a sibling file with ".<lang>" inserted before ".json" (falls back to Arabic
  // content when that sibling doesn't exist yet, exactly like a story without a translation).
  const localize = (url, lang) => (lang === "ar" ? url : url.replace(/\.json$/i, `.${lang}.json`));

  let root = null, cache = { lang: null, items: null, promise: null };

  async function fetchJson(url) {
    try {
      const res = await fetch(url, { cache: "no-store", headers: { Accept: "application/json" } });
      if (!res.ok) return null;
      const v = await res.json();
      return Array.isArray(v) ? v : null;
    } catch (_) { return null; }
  }

  function loadIndex() {
    const lang = LANG();
    if (cache.lang === lang && cache.items) return Promise.resolve(cache.items);
    if (cache.lang === lang && cache.promise) return cache.promise;
    cache.lang = lang;
    cache.promise = Promise.all([
      fetchJson(localize("/data/stories/index.json", lang)),
      fetchJson(localize("/data/academy/index.json", lang))
    ]).then(([stories, academy]) => {
      const items = [];
      if (stories) for (const s of stories) if (s && s.id && s.title) items.push({ type: "story", id: String(s.id), title: String(s.title), blurb: String(s.blurb || ""), tag: String(s.genre || "") });
      if (academy) for (const a of academy) if (a && a.id && a.title) items.push({ type: "academy", id: String(a.id), title: String(a.title), blurb: String(a.blurb || ""), tag: String(a.category || "") });
      cache.items = items;
      return items;
    }).catch(() => (cache.items = []));
    return cache.promise;
  }

  const norm = s => String(s || "").toLowerCase().trim();

  function matches(items, query) {
    const needle = norm(query);
    if (!needle) return [];
    return items.filter(it => norm(it.title).includes(needle) || norm(it.blurb).includes(needle) || norm(it.tag).includes(needle)).slice(0, 20);
  }

  function resultHref(item) {
    const lang = LANG();
    if (item.type === "story") return `/stories/${encodeURIComponent(item.id)}`;
    return lang === "ar" ? `/academy/${encodeURIComponent(item.id)}` : `/academy/${encodeURIComponent(item.id)}/${lang}`;
  }

  function openResult(item) {
    if (item.type === "story") {
      close();
      window.ZIVOZONE_ROOM_LOADER?.ensure("rooms").then(api => api.openStory(item.id)).catch(() => { location.href = resultHref(item); });
    } else {
      location.href = resultHref(item);
    }
  }

  function renderResults(items, query) {
    const list = root.querySelector("[data-search-results]");
    const count = root.querySelector("[data-search-count]");
    if (!query.trim()) {
      list.innerHTML = `<p class="zsearch-hint">${esc(t("searchHint"))}</p>`;
      count.textContent = "";
      return;
    }
    if (!items.length) {
      list.innerHTML = `<p class="zsearch-empty">${esc(fmt("searchNoResults", { query }))}</p>`;
      count.textContent = "";
      return;
    }
    count.textContent = items.length === 1 ? t("searchResultsCountOne") : fmt("searchResultsCount", { count: items.length });
    list.innerHTML = items.map((it, i) => `<a href="${esc(resultHref(it))}" class="zsearch-item" data-search-idx="${i}">
      <span class="zsearch-item-tag">${esc(it.type === "story" ? t("searchStoryTag") : t("searchAcademyTag"))}</span>
      <span class="zsearch-item-body"><b>${esc(it.title)}</b>${it.blurb ? `<small>${esc(it.blurb.slice(0, 110))}${it.blurb.length > 110 ? "…" : ""}</small>` : ""}</span>
    </a>`).join("");
    list.querySelectorAll("[data-search-idx]").forEach(a => a.onclick = e => { e.preventDefault(); openResult(items[Number(a.dataset.searchIdx)]); });
  }

  function render() {
    root.innerHTML = `<div class="zsearch-backdrop" data-search-backdrop>
      <div class="zsearch-card" dir="${esc(dir())}" role="dialog" aria-modal="true" aria-label="${esc(t("searchAria"))}">
        <div class="zsearch-bar"><span class="zsearch-icon">🔍</span>
          <input type="text" id="zsearch-input" placeholder="${esc(t("searchPlaceholder"))}" autocomplete="off" aria-label="${esc(t("searchAria"))}">
          <span class="zsearch-count" data-search-count></span>
          <button type="button" class="zsearch-close" data-search-close aria-label="${esc(t("closeLabel"))}">×</button>
        </div>
        <div class="zsearch-results" data-search-results></div>
      </div>
    </div>`;
    const backdrop = root.querySelector("[data-search-backdrop]");
    const input = root.querySelector("#zsearch-input");
    backdrop.onclick = e => { if (e.target === backdrop) close(); };
    root.querySelector("[data-search-close]").onclick = close;
    let debounce = null;
    input.oninput = () => {
      clearTimeout(debounce);
      const query = input.value;
      debounce = setTimeout(() => loadIndex().then(items => renderResults(matches(items, query), query)), 120);
    };
    renderResults([], "");
    setTimeout(() => input.focus(), 30);
  }

  function open() {
    if (!root) {
      root = document.createElement("div");
      root.id = "zivo-search-overlay";
      root.className = "zsearch-overlay";
      document.body.appendChild(root);
      document.addEventListener("keydown", e => { if (e.key === "Escape" && root?.classList.contains("open")) close(); });
    }
    render();
    root.classList.add("open");
    loadIndex(); // warm the cache immediately, before the first keystroke
  }

  function close() { root?.classList.remove("open"); }

  function mount() {
    const host = document.querySelector(".topbar .top-actions");
    if (host && !document.getElementById("zivo-search-btn")) {
      const b = document.createElement("button");
      b.id = "zivo-search-btn"; b.className = "icon-btn"; b.type = "button";
      b.setAttribute("aria-label", t("searchAria"));
      b.textContent = "🔍";
      b.onclick = open;
      host.insertBefore(b, host.firstChild);
    }
  }

  window.ZIVOZONE_SEARCH = Object.freeze({ __canonical: true, open, close });
  window.ZIVOZONE = window.ZIVOZONE || {};
  window.ZIVOZONE.Search = window.ZIVOZONE_SEARCH;

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", mount); else mount();
})();
